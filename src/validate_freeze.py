#!/usr/bin/env python3
"""validate_freeze.py — freeze-integrity gate, shared across Cascadia modules.

    cascadia-standards template v1.1.0
    Copied verbatim into each module repo. Do not edit this file in a module.
    Everything module-specific lives in governance/freeze.toml.

A Cascadia data module publishes figures with an "as-of" date, and that date is
a claim made out loud — in a portfolio page, in an interview. This script is
what turns "the build did not touch the frozen snapshot" from a promise into a
verified assertion, the same way the whitespace hook in the website repo turns
a remembered rule into a structural one.

It checks one thing, thoroughly:

    every path the module declares frozen is unchanged from the baseline,
    except for paths it explicitly declared as permitted edits — and those are
    printed with their stated reason, so an exception is never silent.

It deliberately does NOT check anything domain-specific. Crossfoot identities,
tie-outs, tag coverage and label honesty belong in the module's own validate
script, because they reference that module's metrics. This runs alongside that
script, not instead of it.

WHAT IS RESOLVED, AND AGAINST WHAT (v1.1.0)
    Each protected pattern is matched against the UNION of three path lists,
    all read from git and none from the filesystem:

        the paths the baseline commit tracks     (git ls-tree -r <baseline>)
        the paths the index tracks now           (git ls-files)
        the paths on disk that git does not track (git ls-files --others)

    and every matched path is then classified:

        in both baseline and index, byte-equal      → unchanged
        in both, differs                            → CHANGED      fails
        in both, missing from the working tree      → DELETED      fails
        in baseline, not in the index               → DELETED      fails
        in the index, not in baseline               → ADDED        fails
        untracked on disk, not in baseline          → ADDED        fails

    A rename is a deletion and an addition and fails twice. A pattern that
    matches nothing in the whole union still fails on its own.

    v1.0.0 resolved patterns against the filesystem and compared only what it
    found there. That passed two cases this gate exists to catch: a file added
    under a protected pattern (resolved, diffed against a baseline that never
    had it, nothing to report), and one of two wildcard siblings deleted (never
    resolved, never checked, the surviving sibling kept the pattern non-empty).
    Both reproduce in test_validate_freeze.py beside this file in
    cascadia-standards, and both now fail.

    Untracked files are not exempt because they are ignored. A frozen directory
    that has acquired a file has changed, whatever .gitignore says about it;
    the report names an ignored file as such so the remedy is obvious.

WHAT "UNCHANGED" MEANS (settled in v1.1.0)
    Protection is byte-for-byte AS GIT STORES THE FILE: the baseline blob
    against the working-tree file after this repository's own line-ending
    normalization (`.gitattributes`, `core.autocrlf`) has been applied. That is
    exactly what `git diff --quiet <baseline> -- <path>` compares, and it is run
    with no whitespace- or line-ending-ignoring flags. So a CRLF rewrite that
    the repository's attributes would normalize away on commit is not a change,
    and one they would commit is — which is the right answer in both cases,
    because what would be committed is what would be published.

    It is therefore NOT byte-for-byte against the disk, and NOT unconditionally
    line-ending-blind. v1.0.0's header said "byte-identical" in one paragraph
    and "line-ending-aware" in another; each was half of this statement.

Usage:
    python src/validate_freeze.py                 # uses governance/freeze.toml
    python src/validate_freeze.py --config <path>
    python src/validate_freeze.py --report <path> # also write a markdown report

Exit code 0 = freeze intact. Exit code 1 = publish nothing, commit nothing.
Any other non-zero exit is the gate refusing to answer (bad config, unknown
baseline, git unavailable) and must be read as a failure, never as a pass.
"""

from __future__ import annotations

import argparse
import re
import subprocess
import sys
import tomllib
from datetime import date
from pathlib import Path

TEMPLATE_VERSION = "1.1.0"

# A gate that crashes while printing its own PASS line reports failure to
# anything reading the exit code. The Windows console defaults to cp1252, which
# cannot encode the en dashes and minus signs in these reports, so a clean run
# died with UnicodeEncodeError and exit 1. Never let formatting decide the
# verdict.
if hasattr(sys.stdout, "reconfigure"):
    sys.stdout.reconfigure(encoding="utf-8", errors="replace")


def repo_root(start: Path) -> Path:
    """The git top level containing `start`."""
    r = subprocess.run(
        ["git", "rev-parse", "--show-toplevel"],
        cwd=start, capture_output=True, text=True,
    )
    if r.returncode != 0:
        sys.exit(f"not inside a git repository: {start}")
    return Path(r.stdout.strip())


def git_ok(root: Path, *args: str) -> bool:
    return subprocess.run(["git", *args], cwd=root, capture_output=True).returncode == 0


def git_paths(root: Path, *args: str) -> set[str]:
    """Run a NUL-delimited path-listing git command and return the paths.

    Fails closed: a git command that cannot answer ends the run with a message
    rather than returning an empty set that would read as "nothing protected".
    """
    r = subprocess.run(["git", *args, "-z"], cwd=root, capture_output=True)
    if r.returncode != 0:
        sys.exit(f"git {' '.join(args)} failed: "
                 f"{r.stderr.decode('utf-8', 'replace').strip()}")
    return {p for p in r.stdout.decode("utf-8", "surrogateescape").split("\0") if p}


def universe(root: Path, baseline: str) -> tuple[set[str], set[str], set[str], set[str]]:
    """The four path sets a pattern is resolved against.

    Returns (baseline_tracked, tracked_now, untracked, untracked_and_ignored);
    the last is a subset of the third and exists only so the report can say
    which it found.
    """
    at_baseline = git_paths(root, "ls-tree", "-r", "--name-only", baseline)
    tracked = git_paths(root, "ls-files")
    others = git_paths(root, "ls-files", "--others")
    unignored = git_paths(root, "ls-files", "--others", "--exclude-standard")
    return at_baseline, tracked, others, others - unignored


def pattern_regex(pattern: str) -> re.Pattern[str]:
    """Translate a repo-relative glob to a whole-path regex.

    Same semantics as pathlib's glob, which v1.0.0 used against the
    filesystem: `*` and `?` never cross a `/`, `**` as a whole segment means
    zero or more directories, and character classes pass through. Written out
    rather than borrowed because glob.translate and PurePath.full_match are
    3.13 and the modules pin nothing newer than tomllib's 3.11.
    """
    segments = pattern.strip("/").split("/")
    out: list[str] = []
    for i, seg in enumerate(segments):
        last = i == len(segments) - 1
        if seg == "**":
            out.append(".*" if last else "(?:[^/]+/)*")
            continue
        body = ""
        j = 0
        while j < len(seg):
            c = seg[j]
            if c == "*":
                body += "[^/]*"
            elif c == "?":
                body += "[^/]"
            elif c == "[":
                k = seg.find("]", j + 1)
                if k == -1:
                    body += re.escape(c)
                else:
                    cls = seg[j + 1:k]
                    if cls.startswith("!"):
                        cls = "^" + cls[1:]
                    body += "[" + cls.replace("\\", "\\\\") + "]"
                    j = k
            else:
                body += re.escape(c)
            j += 1
        out.append(body + ("" if last else "/"))
    return re.compile("^" + "".join(out) + "$")


def resolve(patterns: list[str], paths: set[str]) -> tuple[list[str], list[str]]:
    """Expand glob patterns against a set of repo-relative paths.

    Returns (matched, empty_patterns). A pattern that matches nothing is
    reported rather than ignored: a frozen file that has been deleted or
    renamed is exactly the kind of change this gate exists to catch, and a
    silently-empty protected list would pass with zero checks.
    """
    found: set[str] = set()
    empty: list[str] = []
    for pattern in patterns:
        rx = pattern_regex(pattern)
        matches = [p for p in paths if rx.match(p)]
        if not matches:
            empty.append(pattern)
        found.update(matches)
    return sorted(found), empty


def config_path(root: Path, config: str | None = None) -> Path:
    return Path(config) if config else root / "governance" / "freeze.toml"


def load_config(root: Path, config: str | None = None) -> tuple[dict, Path]:
    """Parse the module's freeze.toml; returns the config and where it came from."""
    path = config_path(root, config)
    if not path.exists():
        sys.exit(f"no freeze config at {path} — see cascadia-standards/templates/freeze.example.toml")
    return tomllib.loads(path.read_text(encoding="utf-8")), path


def load_protected(root: Path, config: str | None = None) -> tuple[list[str], str]:
    """The module's protected paths and baseline, for reuse by its own validator.

    Exposed so a module's domain validation script can report freeze integrity
    in its own report without keeping a second copy of the protected-path list.
    Two copies of that list is precisely how they drift apart unnoticed.
    """
    cfg, _ = load_config(root, config)
    freeze = cfg.get("freeze", {})
    baseline = freeze.get("baseline", "HEAD")
    at_baseline, tracked, others, _ = universe(root, baseline)
    paths, _ = resolve(freeze.get("protected_paths", []), at_baseline | tracked | others)
    exempt = {e["path"] for e in cfg.get("permitted_edit", [])}
    return [p for p in paths if p not in exempt], baseline


def classify(root: Path, baseline: str, path: str,
             at_baseline: set[str], tracked: set[str], ignored: set[str]) -> str | None:
    """One protected path's verdict: None if unchanged, else the failure text."""
    was = path in at_baseline
    now = path in tracked
    on_disk = (root / path).exists()
    if was and now:
        if not on_disk:
            return f"DELETED from the working tree (still in the index): {path}"
        if not git_ok(root, "diff", "--quiet", baseline, "--", path):
            return f"CHANGED since {baseline}: {path}"
        return None
    if was and not now:
        if on_disk:
            return f"DELETED from the index since {baseline} (file still on disk, untracked): {path}"
        return f"DELETED since {baseline}: {path}"
    if now:
        return f"ADDED since {baseline} (tracked): {path}"
    how = "untracked and ignored" if path in ignored else "untracked"
    return f"ADDED since {baseline} ({how}): {path}"


def main() -> int:
    ap = argparse.ArgumentParser(description="Cascadia freeze-integrity gate.")
    ap.add_argument("--config", default=None, help="path to freeze.toml")
    ap.add_argument("--report", default=None, help="also write a markdown report here")
    args = ap.parse_args()

    root = repo_root(Path(__file__).resolve().parent)
    cfg, cfg_path = load_config(root, args.config)
    freeze = cfg.get("freeze", {})
    module = freeze.get("module", root.name)
    as_of = freeze.get("as_of_date", "<unset>")
    baseline = freeze.get("baseline", "HEAD")
    protected_patterns = freeze.get("protected_paths", [])
    permitted = cfg.get("permitted_edit", [])

    if not protected_patterns:
        sys.exit(f"{cfg_path}: freeze.protected_paths is empty — nothing would be checked")

    if not git_ok(root, "rev-parse", "--verify", f"{baseline}^{{commit}}"):
        sys.exit(f"baseline '{baseline}' is not a commit this repo knows about")

    at_baseline, tracked, others, ignored = universe(root, baseline)
    protected, empty_patterns = resolve(protected_patterns, at_baseline | tracked | others)
    exempt = {e["path"] for e in permitted}
    checked = [p for p in protected if p not in exempt]

    verdicts = [classify(root, baseline, p, at_baseline, tracked, ignored) for p in checked]

    # A declared exemption that isn't actually a protected path is a config bug:
    # it reads as though something is being carefully allowed when nothing is.
    stray = sorted(exempt - set(protected))

    failures: list[str] = [v for v in verdicts if v]
    failures += [f"protected_paths pattern matches nothing: {p}" for p in empty_patterns]
    failures += [f"permitted_edit path is not a protected path: {p}" for p in stray]
    ok = not failures

    print(f"Cascadia freeze gate (template v{TEMPLATE_VERSION}) — {module}")
    print(f"  as-of      {as_of}")
    print(f"  baseline   {baseline}")
    print(f"  resolved   against {len(at_baseline)} baseline, {len(tracked)} tracked, "
          f"{len(others)} untracked paths")
    print(f"  protected  {len(checked)} paths checked, {len(exempt)} exempt")
    for e in permitted:
        print(f"  EXEMPT     {e['path']} — {e.get('reason', 'no reason recorded')}")
    for f in failures:
        print(f"  FAIL       {f}")

    if args.report:
        lines = [
            f"# Freeze-integrity report — {module}",
            "",
            f"*Generated by `validate_freeze.py` (cascadia-standards template "
            f"v{TEMPLATE_VERSION}) on {date.today().isoformat()}.*",
            "",
            f"**Overall: {'FREEZE INTACT' if ok else 'FREEZE VIOLATED'}**",
            "",
            f"- Frozen as-of **{as_of}**",
            f"- Compared against **{baseline}**",
            f"- **{len(checked)}** protected paths checked, **{len(exempt)}** declared exempt",
            "",
        ]
        if permitted:
            lines += ["## Declared exemptions", ""]
            lines += [f"- `{e['path']}` — {e.get('reason', 'no reason recorded')}" for e in permitted]
            lines += [""]
        if failures:
            lines += ["## Failures", ""] + [f"- {f}" for f in failures] + [""]
        Path(args.report).write_text("\n".join(lines), encoding="utf-8")
        print(f"  wrote      {args.report}")

    if not ok:
        print("\nPUBLISH GATE: FAILED — the freeze is not intact. Publish nothing, commit nothing.")
        return 1
    print("\nPUBLISH GATE: PASSED — freeze intact.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
